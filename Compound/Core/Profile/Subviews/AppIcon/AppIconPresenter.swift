import SwiftUI

@Observable
@MainActor
class AppIconPresenter {
    
    private let interactor: AppIconInteractor
    private let router: AppIconRouter
    
    init(interactor: AppIconInteractor, router: AppIconRouter) {
        self.interactor = interactor
        self.router = router
    }
    
    func onViewAppear() {
        interactor.trackScreenEvent(event: Event.onAppear)
    }
    
    func onViewDisappear() {
        interactor.trackEvent(event: Event.onDisappear)
    }

}

extension AppIconPresenter {
    enum Event: LoggableEvent {
        case onAppear
        case onDisappear
        
        var eventName: String {
            switch self {
            case .onAppear: return "AppIconView_Appear"
            case .onDisappear: return "AppIconView_Disappear"
            }
        }
        
        var parameters: [String: Any]? {
            switch self {
            default:
                return nil
            }
        }
        
        var type: LogType {
            switch self {
            default:
                return .analytic
            }
        }
    }
}
