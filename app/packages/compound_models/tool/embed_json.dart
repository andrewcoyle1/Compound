// Copies a JSON file into a Dart source file as a string constant, so a
// package can carry the Swift app's data without Flutter assets. Run from
// the package:
//
//   dart run tool/embed_json.dart <source.json> <destination.dart> <name>
//
// The package's tests check the constant is still the file, byte for byte.
import 'dart:io';

void main(List<String> arguments) {
  final [source, destination, name] = arguments;
  final json = File(source).readAsStringSync();
  if (json.contains("'''")) throw ArgumentError('$source holds three quotes');
  final raw = json.contains(r'$') || json.contains(r'\');
  File(destination).writeAsStringSync(
    '// Generated by tool/embed_json.dart from $source; do not edit.\n\n'
    '/// The contents of `${source.split('/').last}`.\n'
    "const $name = ${raw ? 'r' : ''}'''\n$json''';\n",
  );
}
